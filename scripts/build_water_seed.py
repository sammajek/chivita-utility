"""Structure the process-water sampling plan (CHICQARG24) from seed_data/water_analysis_plan_raw.json.

Each test gets: sampling point, sample type, parameter, unit, method, media, frequency,
specification (as written + parsed min/max), alert limit (parsed), action limit (as written).
Writes seed_data/water_plan.json and supabase/seed/40_water_plan.sql.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FREQ = {"weekly": "weekly", "monthly": "monthly", "quarterly": "quarterly", "annually": "annual",
        "fortnightly": "fortnightly"}
NUM = r"[-+]?\d+(?:[.,]\d+)?"


def s(v):
    return re.sub(r"\s+", " ", str(v)).strip() if v not in (None, "") else None


def num(x):
    return float(x.replace(",", ""))


def unit_of(text):
    if not text:
        return None
    for u in ("cfu/250ml", "cfu/100ml", "μS/cm", "ppm", "mg/L", "NTU", "g/cm³", "%"):
        if u.replace(" ", "").lower() in text.replace(" ", "").lower():
            return u
    return None


def parse_limit(text):
    """Returns (min, max, max_inclusive, needs_review)."""
    if not text or text.upper() in ("N/A", "NA"):
        return None, None, True, False
    t = text.replace("–", "-").replace(" to ", "-").replace("≤", "<=").replace("≥", ">=")
    m = re.match(rf"^\s*<\s*({NUM})\s*-\s*({NUM})", t)  # "<3000-5000 ppm"
    if m:
        return None, num(m.group(1)), False, True
    m = re.match(rf"^\s*({NUM})\s*-\s*({NUM})", t)
    if m:
        return num(m.group(1)), num(m.group(2)), True, False
    m = re.match(rf"^\s*<\s*=?\s*({NUM})", t)
    if m:
        return None, num(m.group(1)), "=" in t.split(m.group(1))[0], False
    m = re.match(rf"^\s*>\s*=?\s*({NUM})", t)
    if m:
        return num(m.group(1)), None, True, False
    m = re.match(rf"^\s*({NUM})\s*[a-zA-Zμ%]", t)  # "0 ppm"
    if m:
        return None, num(m.group(1)), True, False
    return None, None, True, True


def main() -> None:
    rows = json.loads((ROOT / "seed_data/water_analysis_plan_raw.json").read_text(encoding="utf-8"))["rows"]
    tests = []
    point = sample = None
    sort = 0
    for r in rows[3:]:
        r = (list(r) + [None] * 15)[:15]
        sn, smp, pt, param = s(r[2]), s(r[3]), s(r[4]), s(r[5])
        if pt:
            point = pt
            sample = smp or (sample if sn is None else None) or "Utilities"
        elif smp:
            sample = smp
        if not param or not point:
            continue
        freq_raw = (s(r[9]) or "").lower()
        freq = FREQ.get(freq_raw, "conditional" if "if " in freq_raw else "weekly")
        spec = s(r[12])
        mn, mx, inc, review = parse_limit(spec)
        alert = s(r[13])
        _, alert_max, _, _ = parse_limit(alert)
        is_text = param.lower().startswith("sensory")
        if is_text:
            mn = mx = None
            review = True
        sort += 1
        tests.append({
            "sort": sort, "point": point, "sample": sample or "Utilities", "param": param,
            "unit": unit_of(spec), "volume": s(r[6]), "method": s(r[7]), "media": s(r[8]),
            "freq": freq, "freq_text": s(r[9]), "incubation": " / ".join(x for x in (s(r[10]), s(r[11]) and f"{s(r[11])} h") if x) or None,
            "spec": spec, "min": mn, "max": mx, "max_incl": inc, "alert_max": alert_max,
            "alert": alert if alert and alert.upper() != "N/A" else None,
            "action": s(r[14]), "text": is_text,
            "review": review or (spec is None and not is_text),
        })
    data = {"document_no": "CHICQARG24", "tests": tests}
    (ROOT / "seed_data/water_plan.json").write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    blob = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    (ROOT / "supabase/seed/40_water_plan.sql").write_text(
        "-- Generated by scripts/build_water_seed.py from seed_data/water_analysis_plan_raw.json\n"
        f"select public.load_water_plan($json${blob}$json$::jsonb);\n", encoding="utf-8")
    pts = sorted({t["point"] for t in tests})
    print(f"{len(tests)} tests at {len(pts)} sampling points; {sum(t['review'] for t in tests)} need review")


if __name__ == "__main__":
    main()
