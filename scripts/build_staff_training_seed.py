"""Build the staff directory and FY2026 training plan seed.

Reads source_files/Utility_Staff_List.xlsx (Sheet2) and
source_files/Training_Needs_for_Utility_Section_FY_2026.xlsx (Sheet1).
Writes seed_data/staff_training.json and supabase/seed/50_staff_training.sql.
Training rows are matched to staff by Staff ID (names are spelled differently in the two files).
"""
import json
import re
from pathlib import Path

import openpyxl

ROOT = Path(__file__).resolve().parent.parent
FY = "FY2026"
YEAR = 2026
MONTHS = {m: i for i, m in enumerate(["january", "february", "march", "april", "may", "june", "july", "august",
                                      "september", "october", "november", "december"], 1)}


def s(v):
    if v is None:
        return None
    v = re.sub(r"\s+", " ", str(v)).strip()
    return v or None


def dates(text):
    """'23 - 27, November' or '30 November - 4 December' → (start, end) ISO dates in YEAR."""
    t = text.lower().replace(",", " ")
    m = re.match(r"\s*(\d{1,2})\s*([a-z]+)?\s*-\s*(\d{1,2})\s*([a-z]+)\s*$", t)
    if not m:
        return None, None
    d1, m1, d2, m2 = m.groups()
    mo2 = MONTHS.get(m2)
    mo1 = MONTHS.get(m1) if m1 else mo2
    if not mo1 or not mo2:
        return None, None
    return f"{YEAR}-{mo1:02d}-{int(d1):02d}", f"{YEAR}-{mo2:02d}-{int(d2):02d}"


def main() -> None:
    staff = []
    ws = openpyxl.load_workbook(ROOT / "source_files/Utility_Staff_List.xlsx", data_only=True)["Sheet2"]
    for row in ws.iter_rows(min_row=4, values_only=True):
        vals = [s(v) for v in row][1:]
        if not vals[0] or not vals[3]:
            continue
        sn, surname, first, sid, band, team = vals[:6]
        staff.append({"staff_id": sid, "surname": surname, "first_name": first,
                      "band": int(float(band)) if band else None, "team": team})

    ws = openpyxl.load_workbook(ROOT / "source_files/Training_Needs_for_Utility_Section_FY_2026.xlsx", data_only=True)["Sheet1"]
    plans, courses = [], {}
    known = {p["staff_id"] for p in staff}
    for row in ws.iter_rows(min_row=6, values_only=True):
        vals = [s(v) for v in row][1:]
        if not vals[0] or not vals[2]:
            continue
        sn, name, sid, course, duration, when, provider = vals[:7]
        start, end = dates(when or "")
        courses.setdefault(course, {"title": course, "provider": provider, "duration": duration})
        plans.append({"staff_id": sid, "name_on_sheet": name, "course": course, "duration": duration, "when": when,
                      "start": start, "end": end, "provider": provider, "fy": FY})
        if sid not in known:
            raise SystemExit(f"Training row for unknown staff ID {sid} ({name})")

    data = {"staff": staff, "courses": list(courses.values()), "plans": plans}
    (ROOT / "seed_data/staff_training.json").write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n")
    sql = ("-- Generated by scripts/build_staff_training_seed.py from source_files/Utility_Staff_List.xlsx and\n"
           "-- source_files/Training_Needs_for_Utility_Section_FY_2026.xlsx\n"
           f"select public.load_staff_training($json${json.dumps(data, separators=(',', ':'), ensure_ascii=False)}$json$::jsonb);\n")
    (ROOT / "supabase/seed/50_staff_training.sql").write_text(sql)
    print(len(staff), "staff,", len(courses), "courses,", len(plans), "plans;",
          sum(1 for p in plans if not p["start"]), "plans without parsed dates")


if __name__ == "__main__":
    main()
